import { z } from "zod";

const boundedInteger = (fallback: number, minimum: number, maximum: number) =>
  z.string().regex(/^\d+$/).transform(Number).pipe(
    z.number().int().min(minimum).max(maximum),
  ).default(fallback);

const loopbackHost = z.string().min(1).max(253).refine((host) => {
  if (host === "localhost" || host === "0.0.0.0") return true;
  if (/^\d{1,3}(?:\.\d{1,3}){3}$/.test(host)) {
    const parts = host.split(".").map(Number);
    if (parts.some((part) => part > 255)) return false;
    return parts[0] === 127;
  }
  if (host === "::1") return true;
  return false;
}, "SANDBOX_CONTROLLER_HOST must be loopback or 0.0.0.0 on an internal Compose network");

const imageDigest = z.string().min(1).max(300).regex(
  /^(?:[A-Za-z0-9._:/-]+@sha256:[a-f0-9]{64}|sha256:[a-f0-9]{64})$/,
  "SANDBOX_IMAGE must be pinned to a sha256 digest or immutable local image ID",
);

const egressAllowlist = z.string().max(2048).default("registry.npmjs.org").transform((value) =>
  value.split(",").map((host) => host.trim().toLowerCase()).filter(Boolean),
).pipe(z.array(z.string().min(1).max(253)).min(1).max(16).refine((hosts) => {
  if (new Set(hosts).size !== hosts.length) return false;
  return hosts.every((host) => {
    const labels = host.split(".");
    return labels.length >= 2 && labels.every((label) => label.length <= 63 && /^[a-z0-9](?:[a-z0-9-]*[a-z0-9])?$/.test(label)) &&
      !["localhost", "local", "internal", "test", "example", "invalid", "home.arpa", "lan", "corp"].some((suffix) =>
        host === suffix || host.endsWith(`.${suffix}`)) &&
      !/^\d{1,3}(?:\.\d{1,3}){3}$/.test(host);
  });
}, "SANDBOX_EGRESS_ALLOWLIST must contain exact public DNS names").refine(
  (hosts) => hosts.includes("registry.npmjs.org"),
  "SANDBOX_EGRESS_ALLOWLIST must include registry.npmjs.org",
));

export const SandboxEnvironmentSchema = z.object({
  SANDBOX_DRIVER: z.enum(["disabled", "rootless"]).default("disabled"),
  SANDBOX_IMAGE: imageDigest,
  SANDBOX_CONTROLLER_TOKEN: z.string().min(32).max(256).refine(
    (value) => !/placeholder|replace-me|change-me/i.test(value),
    "SANDBOX_CONTROLLER_TOKEN must be generated by the operator",
  ),
  SANDBOX_CONTROLLER_HOST: loopbackHost.default("127.0.0.1"),
  SANDBOX_CONTROLLER_PORT: boundedInteger(8081, 1, 65535),
  SANDBOX_DOCKER_SOCKET: z.string().min(1).max(255).default("/run/user/1000/docker.sock"),
  SANDBOX_HOST_RUNTIME_MODE: z.enum(["rootless", "docker-desktop-security"]).default("rootless"),
  SANDBOX_WORKSPACE_MODE: z.enum(["user-quota", "tmpfs"]).default("user-quota"),
  SANDBOX_CPU_LIMIT: boundedInteger(1, 1, 8),
  SANDBOX_MEMORY_MB: boundedInteger(1024, 256, 8192),
  SANDBOX_DISK_MB: boundedInteger(2048, 128, 16_384),
  SANDBOX_PIDS_LIMIT: boundedInteger(128, 16, 1024),
  SANDBOX_COMMAND_TIMEOUT_MS: boundedInteger(60_000, 1_000, 120_000),
  SANDBOX_EGRESS_ALLOWLIST: egressAllowlist,
  SANDBOX_IDLE_TTL_SECONDS: boundedInteger(900, 60, 86_400),
}).strict();

export type SandboxEnvironment = z.infer<typeof SandboxEnvironmentSchema>;

const keys = Object.keys(SandboxEnvironmentSchema.shape) as Array<keyof typeof SandboxEnvironmentSchema.shape>;

export function parseSandboxEnvironment(source: Record<string, string | undefined>): SandboxEnvironment {
  const result = SandboxEnvironmentSchema.safeParse(Object.fromEntries(keys.map((key) => [key, source[key]])));
  if (!result.success) {
    const fields = [...new Set(result.error.issues.map((issue) => issue.path.join(".")))];
    throw new Error(`Invalid sandbox environment fields: ${fields.join(", ")}`);
  }
  return result.data;
}
